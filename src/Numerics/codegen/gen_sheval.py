#! /usr/bin/env python3
"""Generate the explicitly unrolled real solid harmonic evaluation in
src/Numerics/SoaSphericalTensor.h -- the SHEval0..SHEval<LMAX> family and the
SHEval dispatch function.

This implements the code generation scheme of

  Sloan, P., Efficient Spherical Harmonic Evaluation,
  Journal of Computer Graphics Techniques, vol. 2, no. 2, 84-90, 2013.

with one generalization the paper does not cover.  The paper evaluates on the
unit sphere, so its supplemental generator emits a bare constant wherever a
power of r^2 would go, and cannot produce this code as it stands.  QMCPACK's
basis needs the homogeneous solid harmonics r^l Y_lm, so every such term is
emitted as a multiple of fR2 instead and each SHEval function is a homogeneous
polynomial of degree Lmax.

Usage
  gen_sheval.py            check that SoaSphericalTensor.h matches this generator
  gen_sheval.py --write    rewrite the generated block in SoaSphericalTensor.h
  gen_sheval.py --tests    rewrite the generated unit test, tests/test_sheval.cpp
  gen_sheval.py --verify N validate the emitted code against SymPy's Ynm

On the constants.  Sloan notes that a naive evaluation of K(l,m) loses accuracy
at high l and recommends arbitrary precision, so every coefficient here is
evaluated exactly with mpmath and rounded exactly once, on print, to the
shortest decimal that round-trips to the intended double.

The literals committed to SoaSphericalTensor.h were printed by the original C++
generator, which computed them in long double and printed 32 significant digits.
A C++ floating literal with no suffix has type double, so everything past the
17th digit is discarded by the compiler and the two forms are the same number:
--check therefore compares constants as IEEE-754 doubles rather than as text,
and reports 2682 of 2682 identical.  Running --write reflows those literals to
their shortest round-tripping form; the compiled result is unchanged.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

from mpmath import mp, mpf, pi, sqrt

# Highest angular momentum to unroll.  SHEval has no case beyond this.
LMAX = 19

# mpmath working precision.  Well beyond double; coefficients round once, on print.
mp.prec = 300

BEGIN = "// ---- BEGIN generated by src/Numerics/codegen/gen_sheval.py -- DO NOT EDIT ----"
END = "// ---- END generated by src/Numerics/codegen/gen_sheval.py ----"


# --------------------------------------------------------------- coefficients

def index(l, m):
    """Storage index for a real solid harmonic: i = l(l+1) + m."""
    return l * (l + 1) + m


def normalization(l, m):
    """K(l,m) = sqrt((2l+1)(l-|m|)! / (4 pi (l+|m|)!)); Listing 1 of the paper.

    The factorials are taken as a ratio so that neither one overflows on its own.
    """
    ratio = mpf(1)
    for k in range(l + abs(m), l - abs(m), -1):
        ratio *= k
    return sqrt((2 * mpf(l) + 1) / (4 * pi * ratio))


def prefactor(l, m):
    """The sqrt(2) K(l,m) prefactor of Eq. (1).  The sqrt(2) is absent for m = 0."""
    return sqrt(mpf(2)) * normalization(l, m) if m else normalization(l, m)


def diagonal(m):
    """Eq. (4a): P_m^m = (1-2m) P_{m-1}^{m-1}, with sin^m(theta) factored out.

    Factoring out sin^m(theta) is Snyder's trick: it leaves a polynomial in z,
    and the sin^m(theta) is absorbed into the (x, y) tower built by the
    trigonometric addition theorem.
    """
    value = mpf(1)
    for k in range(1, m + 1):
        value *= 1 - 2 * k
    return value


def coefficients(l, m):
    """Constants emitted for the (l, m) term, in source order.

    The shape depends only on l - m and follows the paper's recurrences:

      l - m == 0   Eq. (4a)   c
      l - m == 1   Eq. (4b)   c z
      l - m == 2   Eq. (4d)   a z^2 + b r^2
      l - m == 3   Eq. (4e)   z (a z^2 + b r^2)
      l - m >= 4   Eq. (4c)   A z P_{l-1}^m + B r^2 P_{l-2}^m

    Equations (4d) and (4e) are (4c) with (4a) and (4b) substituted in and the
    constants folded, which is what lets the first four terms of each tower be
    emitted without referring back to anything.

    The l - m >= 4 coefficients absorb the ratio of normalizations, because the
    terms they refer back to already carry their own K.
    """
    d, pre, diag = l - m, prefactor(l, m), diagonal(m)
    if d == 0:
        return [pre * diag]
    if d == 1:
        return [pre * (2 * m + 1) * diag]
    if d == 2:
        return [pre * (2 * m + 3) * (2 * m + 1) * diag / 2,
                -pre * (2 * m + 1) * diag / 2]
    if d == 3:
        return [pre * (2 * m + 5) * (2 * m + 3) * (2 * m + 1) * diag / 6,
                -pre * 3 * (4 * m * m + 8 * m + 3) * diag / 6]
    return [sqrt(mpf((2 * l + 1) * (2 * l - 1)) / mpf((l + m) * (l - m))),
            -sqrt(mpf((2 * l + 1) * (l + m - 1) * (l - m - 1))
                  / mpf((2 * l - 3) * (l + m) * (l - m)))]


def literal(value):
    """Shortest decimal string that round-trips to the intended double."""
    text = repr(float(mp.mpf(value)))
    return text[:-2] if text.endswith(".0") else text


# ------------------------------------------------------------- code emission

def temp_name(l, m, lmax):
    """Scratch variable holding the (l, m) coefficient.

    Cycles fTmpA/B/C with l - m so that the two terms a recurrence step reads are
    still live.  The final band (m == lmax) is a single term consumed
    immediately, and the generator this replaces emitted it on a different
    letter; that is reproduced here so the output matches.  Any letter is correct.
    """
    if m == lmax:
        return "fTmpB" if lmax == 1 else "fTmpC"
    return "fTmp" + "ABC"[(l - m) % 3]


def expression(l, m, previous, second_previous):
    """Right-hand side for the (l, m) coefficient."""
    d = l - m
    c = [literal(v) for v in coefficients(l, m)]
    if d == 0:
        return c[0]
    if d == 1:
        return f"{c[0]} * fZ"
    if d == 2:
        return f"{c[0]} * fZ2 + {c[1]} * fR2"
    if d == 3:
        return f"fZ * ({c[0]} * fZ2 + {c[1]} * fR2)"
    return f"{c[0]} * fZ * {previous} + {c[1]} * {second_previous} * fR2"


def sheval(lmax):
    """Emit SHEval<lmax>."""
    out = [f"// Lmax == {lmax}",
           "template<typename T>",
           f"void SHEval{lmax}(const T fX, const T fY, const T fZ, T* pSH)",
           "{",
           "  T fC0, fC1, fS0, fS1, fTmpA, fTmpB, fTmpC;"]
    if lmax >= 2:
        out.append("  T fZ2 = fZ * fZ;")
        out.append("  T fR2 = fX * fX + fY * fY + fZ * fZ;")
    else:
        out.append("")

    # m == 0 has no (x, y) dependence, so it is written straight into pSH and the
    # recurrence reads back out of pSH rather than out of a scratch variable.
    for l in range(lmax + 1):
        rhs = expression(l, 0, f"pSH[{index(l - 1, 0)}]", f"pSH[{index(l - 2, 0)}]")
        out.append(f"  pSH[{index(l, 0)}] = {rhs};")
    out.append("  fC0 = fX;")
    out.append("  fS0 = fY;")

    # m >= 1: one coefficient tower per m, paired with Re/Im (x + iy)^m.
    for m in range(1, lmax + 1):
        out.append("")
        cos_name, sin_name = f"fC{(m - 1) % 2}", f"fS{(m - 1) % 2}"
        for l in range(m, lmax + 1):
            name = temp_name(l, m, lmax)
            rhs = expression(l, m, temp_name(l - 1, m, lmax), temp_name(l - 2, m, lmax))
            out.append(f"  {name} = {rhs};")
            out.append(f"  pSH[{index(l, m)}] = {name} * {cos_name};")
            out.append(f"  pSH[{index(l, -m)}] = {name} * {sin_name};")
        if m < lmax:
            out.append(f"  fC{m % 2} = fX * {cos_name} - fY * {sin_name};")
            out.append(f"  fS{m % 2} = fX * {sin_name} + fY * {cos_name};")
    out.append("}")
    return "\n".join(out)


def dispatch(lmax):
    """Emit the SHEval dispatch function."""
    out = ["// auxiliary function",
           "template<typename T>",
           "void SHEval(const T fX0, const T fY0, const T fZ, T* pSH, const int l_max, bool addsign)",
           "{",
           "  T fX, fY;",
           "  if (addsign)",
           "  {",
           "    fX = -1.0L * fX0;",
           "    fY = -1.0L * fY0;",
           "  }",
           "  else",
           "  {",
           "    fX = fX0;",
           "    fY = fY0;",
           "  }",
           "  switch (l_max)",
           "  {"]
    for l in range(lmax + 1):
        if l:
            out.append("")
        out.append(f"  case {l}:")
        out.append(f"    SHEval{l}(fX, fY, fZ, pSH);")
        out.append("    break;")
    out.append("  }")
    out.append("}")
    return "\n".join(out)


def generated_block():
    """The whole generated region, without the markers."""
    header = ["// Explicitly unrolled functions based on:",
              "// Sloan, P., Efficient Spherical Harmonic Evaluation, Journal of Computer "
              "Graphics Techniques, vol. 2, no. 2, 84-90, 2013"]
    body = [sheval(l) for l in range(LMAX + 1)] + [dispatch(LMAX)]
    return "\n".join(header) + "\n" + "\n\n".join(body)


# ------------------------------------------------------------------ file I/O

def header_path():
    return Path(__file__).resolve().parent.parent / "SoaSphericalTensor.h"


def style_path():
    """QMCPACK's clang-format configuration, src/.clang-format."""
    return Path(__file__).resolve().parent.parent.parent / ".clang-format"


def clang_format(text):
    """Run clang-format over a standalone fragment.

    The generated block is formatted on its own rather than by reformatting the
    whole header, so that a clang-format version newer than the one the rest of
    the file was written with does not churn unrelated lines.  The style file is
    named explicitly because clang-format otherwise searches upward from the
    input file, which finds nothing in a temporary directory.
    """
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        fragment = Path(tmp) / "fragment.h"
        fragment.write_text(text, encoding="utf-8")
        subprocess.run(["clang-format", f"--style=file:{style_path()}", "-i", str(fragment)],
                       check=True)
        return fragment.read_text()


def splice(text, block):
    """Replace the marked region of the header with block."""
    start, end = text.index(BEGIN), text.index(END)
    return text[:start] + BEGIN + "\n" + block + text[end:]


def rendered():
    """The generated region, formatted, as it should appear in the header."""
    return clang_format(generated_block())


def write():
    path = header_path()
    path.write_text(splice(path.read_text(), rendered()), encoding="utf-8")
    print(f"wrote {path}")


NUMBER = re.compile(r"-?\d+\.\d+(?:[eE][-+]?\d+)?")


def check():
    """Compare the header on disk against a fresh generation.

    Constants are compared as doubles rather than as text, so a header whose
    literals were printed by a different generator still passes as long as every
    one of them parses to the same double.
    """
    import struct

    text = header_path().read_text()
    have = text[text.index(BEGIN) + len(BEGIN):text.index(END)].strip("\n").splitlines()
    want = rendered().strip("\n").splitlines()

    if len(have) != len(want):
        sys.exit(f"line count differs: {len(have)} on disk vs {len(want)} generated")

    constants = 0
    for n, (a, b) in enumerate(zip(have, want), 1):
        if NUMBER.sub("K", a) != NUMBER.sub("K", b):
            sys.exit(f"line {n} of the generated block differs:\n  on disk   {a}\n  generated {b}")
        for i, j in zip(NUMBER.findall(a), NUMBER.findall(b)):
            if struct.pack("<d", float(i)) != struct.pack("<d", float(j)):
                sys.exit(f"line {n}: {i} and {j} are different doubles")
            constants += 1
    print(f"identical: {len(have)} lines, {constants} constants equal as doubles")


