# --------------------------------------------------------------- unit tests

# Four points: the z axis, where every m != 0 term vanishes identically, the
# point the hand-written tensor tests already use, and two off-axis points with
# no symmetry.  One reference table covers every (l, m) up to LMAX, and SHEval<n>
# is checked against its first (n+1)^2 entries, so the twenty functions are also
# checked for consistency with one another.
TEST_POINTS = ((0.0, 0.0, 1.0),
               (1.3, 1.2, -0.5),
               (-0.52854, -1.04749, 0.45281),
               (-1.32601, 0.02232, -1.38753))

# The recurrence chain loses about a digit per few bands; the measured worst
# case at LMAX == 19 is 1e-13 relative, so this leaves two orders of headroom
# for a compiler that contracts differently.
TEST_EPSILON = 1e-11
TEST_MARGIN = 1e-11


def tests_path():
    return Path(__file__).resolve().parent.parent / "tests" / "test_sheval.cpp"


def reference_value(l, m, point):
    """r^l S_l^m at point, in the addsign == false convention.

    Built from mpmath's spherical harmonic rather than from the recurrences this
    script emits, so the generated code is checked against an independent
    definition and not against itself.
    """
    from mpmath import acos, atan2, spherharm

    x, y, z = (mpf(c) for c in point)
    r = sqrt(x * x + y * y + z * z)
    value = spherharm(l, abs(m), acos(z / r), atan2(y, x))
    if m == 0:
        angular = value.real
    else:
        angular = sqrt(mpf(2)) * (value.real if m > 0 else value.imag)
    return angular * r**l


def reference_table():
    """One row of (LMAX + 1)^2 values per test point, in storage order."""
    return [[reference_value(l, m, point)
             for l in range(LMAX + 1) for m in range(-l, l + 1)]
            for point in TEST_POINTS]


def table(rows, per_line=4):
    """A brace-enclosed C++ initializer for a two-dimensional double array."""
    out = []
    for i, row in enumerate(rows):
        literals = [literal(v) for v in row]
        chunks = [", ".join(literals[j:j + per_line]) for j in range(0, len(literals), per_line)]
        body = (",\n" + " " * 5).join(chunks)
        out.append("    {" + body + "}" + ("," if i + 1 < len(rows) else ""))
    return "{\n" + "\n".join(out) + "}"


def test_source():
    """The complete generated unit test."""
    values = reference_table()
    return (TEST_TEMPLATE
            .replace("%LMAX", str(LMAX))
            .replace("%NPOINTS", str(len(TEST_POINTS)))
            .replace("%EPSILON", repr(TEST_EPSILON))
            .replace("%MARGIN", repr(TEST_MARGIN))
            .replace("%POINTS", table([list(p) for p in TEST_POINTS], per_line=3))
            .replace("%VALUES", table(values)))


def write_tests():
    path = tests_path()
    path.write_text(clang_format(test_source()), encoding="utf-8")
    print(f"wrote {path} ({len(TEST_POINTS)} points, {(LMAX + 1) ** 2} terms each)")


def check_tests():
    path = tests_path()
    if not path.exists():
        return
    if path.read_text(encoding="utf-8") != clang_format(test_source()):
        sys.exit(f"{path} is stale; regenerate with gen_sheval.py --tests")
    print(f"identical: {path.name}")


# ---------------------------------------------------------------- validation

def verify(lmax=6, points=200, tolerance=1e-11):
    """Check the emitted code against SymPy's spherical harmonics.

    The generated statements are translated to Python and evaluated in double
    precision, and compared against r^l times the real spherical harmonic built
    from SymPy's Ynm, evaluated at 50 digits.  This validates the generated
    source itself -- its constants, its statement order and its indexing -- and
    not merely the recurrences it was produced from.

    The residual is the double-precision round-off of the recurrence chain, so
    the comparison is numerical; it grows slowly with lmax.
    """
    import random

    from mpmath import mpf, nstr
    from sympy import (Integer, Symbol, cos, expand, expand_complex, expand_func,
                       expand_trig, lambdify, powdenest, simplify, sin)
    from sympy import im as sympy_im, re as sympy_re, sqrt as sympy_sqrt

    x, y, z = (Symbol(s, real=True) for s in "xyz")
    r, rho = Symbol("r", positive=True), Symbol("rho", positive=True)
    theta, phi = Symbol("theta", real=True), Symbol("phi", real=True)

    def reference(l, m):
        """r^l S_l^m, without the (-1)^m the generated code leaves out."""
        if m == 0:
            angular = expand_func(Ynm(l, 0, theta, phi))
        else:
            full = expand_complex(expand_func(Ynm(l, abs(m), theta, phi)))
            angular = sympy_sqrt(2) * (sympy_re(full) if m > 0 else sympy_im(full))
        e = expand(expand_trig(angular) * r**l)
        e = e.subs({cos(phi): x / rho, sin(phi): y / rho,
                    cos(theta): z / r, sin(theta): rho / r}, simultaneous=True)
        e = expand(e).subs(rho**2, x**2 + y**2).subs(r**2, x**2 + y**2 + z**2)
        e = powdenest(e, force=True)
        return expand(simplify(e.subs(rho, sympy_sqrt(x**2 + y**2))
                               .subs(r, sympy_sqrt(x**2 + y**2 + z**2))))

    from sympy.functions.special.spherical_harmonics import Ynm

    # translate the emitted C++ into a Python function evaluated in float64
    body = []
    for line in sheval(lmax).splitlines():
        s = line.strip().rstrip(";")
        if not s or s.startswith(("//", "template", "void", "{", "}")):
            continue
        s = re.sub(r"^T\s+", "", s)
        if " = " not in s:            # the scratch-variable declaration
            continue
        body.append("    " + s)
    source = (f"def evaluate(fX, fY, fZ):\n"
              f"    pSH = [0.0] * {(lmax + 1) ** 2}\n" + "\n".join(body) + "\n    return pSH\n")
    namespace = {}
    exec(source, namespace)
    evaluate = namespace["evaluate"]

    exact = {(l, m): lambdify((x, y, z), reference(l, m), "mpmath")
             for l in range(lmax + 1) for m in range(-l, l + 1)}

    random.seed(0)
    worst, where = 0.0, None
    for _ in range(points):
        px, py, pz = (random.uniform(-1.5, 1.5) for _ in range(3))
        emitted = evaluate(px, py, pz)
        for (l, m), fn in exact.items():
            want = fn(mpf(px), mpf(py), mpf(pz))
            error = abs(mpf(emitted[index(l, m)]) - want) / max(abs(want), mpf(1))
            if error > worst:
                worst, where = error, (l, m)
    print(f"SHEval{lmax}: {(lmax + 1) ** 2} terms, {points} points, "
          f"max relative error {nstr(worst, 3)} (worst at l={where[0]} m={where[1]})")
    if worst > tolerance:
        sys.exit(f"exceeds tolerance {tolerance}")


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true",
                        help="rewrite the generated block in SoaSphericalTensor.h")
    parser.add_argument("--tests", action="store_true",
                        help="rewrite the generated unit test in tests/test_sheval.cpp")
    parser.add_argument("--verify", type=int, nargs="?", const=6, metavar="LMAX",
                        help="validate the emitted code against SymPy (default lmax 6)")
    args = parser.parse_args()
    if args.verify is not None:
        verify(args.verify)
    elif args.write:
        write()
    elif args.tests:
        write_tests()
    else:
        check()
        check_tests()


if __name__ == "__main__":
    main()
